#!/usr/bin/env node
/* Every line the game can speak, with the audio file each one plays (7-1).

   node tools/voice-lines.js           print audio/lines.tsv (file, key, text to record)
   node tools/voice-lines.js clips     write clips.js from the files that exist in audio/

   Symbol sounds (audio/sym/NN.mp3, NN = position in ORDER) come from the Ministry of Education
   《國語注音符號手冊》開放部件, CC BY 4.0. Other lines are rendered with Edge voices (see DECISIONS.md).

   The key must match clipKey() in app.js: the text without punctuation.
   tests/voice.js plays lessons and fails if the game asks for a key that is not listed here. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(ROOT, 'data.js'), 'utf8') + ';this.D={SYM,ORDER,UNITS,PRAISE,TONE_NAME}', ctx);
const { SYM, ORDER, UNITS, PRAISE, TONE_NAME } = ctx.D;

const clipKey = t => String(t).replace(/[！？，。、「」：\s!?,.:]/g, '');
const wordText = s => SYM[s].w.map(x => x[0]).join('');

// Fixed lines in app.js. Text is what gets recorded; punctuation only shapes the reading.
const FIXED = [
  '注音小學堂', '要離開嗎？',
  ...PRAISE, '再想想看！', '沒關係，再試一次！', '慢慢來，你可以的！',
  '答案在這裡！', '下次一定可以！', '對！', '完美過關！', '完成了，你好棒！',
  '這是新朋友！', '聽一聽，是哪一個注音？', '少了哪一個注音？', '沿著藍色的字，寫寫看。',
  '把所有的這個注音戳破！', '寫得好漂亮！', '寫得很好！', '很努力喔！我們繼續！', '全部找到了！',
  '兩個注音拼在一起，會變成什麼？', '聽一聽，是哪一個拼音？', '前面要放哪一個注音？',
  '同一個拼音，有四種唱法。', '聽一聽，是第幾聲？',
];

function lines() {
  const out = [], seen = new Set();
  const add = (kind, text, key = clipKey(text)) => {
    if (seen.has(key)) return; seen.add(key);
    const file = kind === 'sym'
      ? `sym/${String(ORDER.indexOf(key.slice(4)) + 1).padStart(2, '0')}.mp3`
      : `v/${kind}-${String(out.filter(l => l.kind === kind).length + 1).padStart(3, '0')}.mp3`;
    out.push({ kind, key, text, file });
  };
  FIXED.forEach(t => add('line', t));
  ORDER.forEach(s => add('word', wordText(s) + '。'));
  UNITS.forEach(u => (u.sets || []).forEach(set => set.forEach(it => {
    if (u.kind === 'blend') add('char', it[2] + '。');
  })));
  UNITS.filter(u => u.kind === 'tone').forEach(u => u.sets.forEach(set => set.forEach(([ch], k) => {
    add('char', ch + '。');
    add('line', `對！「${ch}」是${TONE_NAME[k]}。`);
    add('line', `「${ch}」是${TONE_NAME[k]}。`); // after two misses the game drops 對！
  })));
  ORDER.forEach(s => add('sym', s, 'sym:' + s));
  return out;
}

if (require.main === module) {
  const L = lines();
  if (process.argv[2] === 'clips') {
    const map = {};
    for (const l of L) {
      if (fs.existsSync(path.join(ROOT, 'audio', l.file))) map[l.key] = l.file;
    }
    fs.writeFileSync(path.join(ROOT, 'clips.js'),
      '/* Generated by tools/voice-lines.js. Line key -> file in audio/. Missing lines use speech synthesis. */\n' +
      'const CLIPS=' + JSON.stringify(map, null, 0).replace(/","/g, '",\n"') + ';\n');
    console.error(`clips.js: ${Object.keys(map).length} of ${L.length} lines have a clip`);
  } else {
    console.log('file\tkey\ttext');
    for (const l of L) console.log(`${l.file}\t${l.key}\t${l.text}`);
  }
}
module.exports = { lines, clipKey };
